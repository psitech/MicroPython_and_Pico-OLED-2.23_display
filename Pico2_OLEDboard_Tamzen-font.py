class SSD1305_SPI(framebuf.FrameBuffer):
    def __init__(self):
        self.width = 128
        self.height = 32
        
        self.cs = Pin(9, Pin.OUT)
        self.rst = Pin(12, Pin.OUT)
        
        self.cs(1)
        self.spi = SPI(1, 10000_000, polarity=0, phase=0, sck=Pin(10), mosi=Pin(11), miso=None)
        self.dc = Pin(8, Pin.OUT)
        self.dc(1)
        self.buffer = bytearray(self.height * self.width // 8)
        super().__init__(self.buffer, self.width, self.height, framebuf.MONO_VLSB)
        self.init_display()
        
        self.white = 0xffff
        self.black = 0x0000
        
    def write_cmd(self, cmd):
        self.cs(1)
        self.dc(0)
        self.cs(0)
        self.spi.write(bytearray([cmd]))
        self.cs(1)

    def write_data(self, buf):
        self.cs(1)
        self.dc(1)
        self.cs(0)
        self.spi.write(bytearray([buf]))
        self.cs(1)

    def init_display(self):
        self.rst(1)
        time.sleep(0.001)
        self.rst(0)
        time.sleep(0.01)
        self.rst(1)
        
        for cmd in [0xAE, 0x04, 0x10, 0x40, 0x81, 0x80, 0xA1, 0xA6, 0xA8, 0x1F, 
                    0xC8, 0xD3, 0x00, 0xD5, 0xF0, 0xD8, 0x05, 0xD9, 0xC2, 0xDA, 
                    0x12, 0xDB, 0x08, 0xAF]:
            self.write_cmd(cmd)

    def show(self):
        for page in range(0, 4):
            self.write_cmd(0xb0 + page)
            self.write_cmd(0x04)
            self.write_cmd(0x10)
            self.dc(1)
            for num in range(0, 128):
                self.write_data(self.buffer[page * 128 + num])

    def draw_text(self, text, start_x, start_y):
        current_x = start_x
        for char in text:
            ord_ch = ord(char)
            if ord_ch < 32 or ord_ch > 126:
                ord_ch = 32
                
            offset = (ord_ch - 32) * 13
            char_bytes = Font_Tamzen8X15r[offset : offset + 13]
            
            # fast native layout block injection
            char_fbuf = framebuf.FrameBuffer(char_bytes, 8, 13, framebuf.MONO_HLSB)
            self.blit(char_fbuf, current_x, start_y)
            current_x += 8

